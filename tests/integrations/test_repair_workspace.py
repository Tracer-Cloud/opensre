def _git(path: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(path), *args], check=True, capture_output=True, text=True
    ).stdout.strip()


@pytest.fixture
def remote(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    source = tmp_path / "source"
    source.mkdir()
    _git(source, "init", "-b", "main")
    _git(source, "config", "user.name", "Test")
    _git(source, "config", "user.email", "test@example.com")
    (source / "calculator.py").write_text("def add(a, b): return a - b\n")
    _git(source, "add", ".")
    _git(source, "commit", "-m", "fixture")
    _git(source, "branch", "demo/failing-ci")
    monkeypatch.setenv("GIT_CONFIG_COUNT", "3")
    monkeypatch.setenv("GIT_CONFIG_KEY_0", f"url.{source}.insteadOf")
    monkeypatch.setenv("GIT_CONFIG_VALUE_0", "https://github.com/acme/demo.git")
    monkeypatch.setenv("GIT_CONFIG_KEY_1", "user.name")
    monkeypatch.setenv("GIT_CONFIG_VALUE_1", "Test")
    monkeypatch.setenv("GIT_CONFIG_KEY_2", "user.email")
    monkeypatch.setenv("GIT_CONFIG_VALUE_2", "test@example.com")
