def test_remote_repairs_have_isolated_checkouts_and_owned_cleanup(
    remote: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    unrelated = tmp_path / "unrelated"
    unrelated.mkdir()
    _git(unrelated, "init")
    _git(unrelated, "remote", "add", "origin", "https://github.com/Tracer-Cloud/opensre.git")
    monkeypatch.chdir(unrelated)
    with repair_workspace("acme", "demo", root=tmp_path / "repairs") as first:
        with repair_workspace("acme", "demo", root=tmp_path / "repairs") as second:
            assert first != second
            assert _git(first, "remote", "get-url", "origin") == str(remote)
            (first / "calculator.py").write_text("changed\n")
            cache = first / "__pycache__"
            cache.mkdir()
            (cache / "calculator.cpython-313.pyc").write_bytes(b"generated by tests")
            assert changed_paths(str(first)) == ["calculator.py"]
            assert (second / "calculator.py").read_text() == "def add(a, b): return a - b\n"
        assert not second.exists()
        assert first.exists()
    assert not first.exists()
    assert unrelated.exists()


@pytest.mark.parametrize("mismatched_push_url", [False, True])
def test_explicit_mismatched_workspace_is_preserved(
    tmp_path: Path, mismatched_push_url: bool
) -> None:
    _git(tmp_path, "init")
    _git(
        tmp_path,
        "remote",
        "add",
        "origin",
        "https://github.com/acme/demo.git"
        if mismatched_push_url
        else "https://github.com/other/project.git",
    )
    if mismatched_push_url:
        _git(tmp_path, "config", "remote.origin.pushurl", "https://github.com/other/project.git")
    marker = tmp_path / "uncommitted.txt"
    marker.write_text("user work")
    with (
        pytest.raises(GitCommandError, match="Workspace origin"),
        repair_workspace("acme", "demo", workspace=str(tmp_path)),
    ):
        pytest.fail("mismatched checkout was accepted")
    assert marker.read_text() == "user work"


def test_same_target_is_exclusive_and_released_after_failure(remote: Path, tmp_path: Path) -> None:
    def concurrent_repair() -> None:
        with (
            pytest.raises(GitCommandError, match="Another repair"),
            repair_workspace("acme", "demo", target="demo/failing-ci", root=tmp_path),
        ):
            pytest.fail("concurrent repair acquired the target")

    with (
        pytest.raises(RuntimeError, match="interrupted"),
        repair_workspace("acme", "demo", target="demo/failing-ci", root=tmp_path),
    ):
        with ThreadPoolExecutor(max_workers=1) as pool:
            pool.submit(concurrent_repair).result(timeout=10)
        raise RuntimeError("interrupted")
    with repair_workspace("acme", "demo", target="demo/failing-ci", root=tmp_path) as path:
        assert path.exists()


def test_changed_checkout_revision_cannot_be_repaired(remote: Path, tmp_path: Path) -> None:
    original = _git(remote, "rev-parse", "HEAD")
    _git(remote, "commit", "--allow-empty", "-m", "another author")
    with (
        repair_workspace("acme", "demo", root=tmp_path) as path,
        pytest.raises(GitCommandError, match="revision changed"),
    ):
        ensure_head_revision(str(path), original)


def test_ci_repair_from_an_unrelated_directory_pushes_and_verifies_target(
    remote: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    ctx = replace(
        _CTX,
        owner="acme",
        repo="demo",
        number=1,
        head_branch="demo/failing-ci",
        head_sha=_git(remote, "rev-parse", "HEAD"),
    )
    unrelated = tmp_path / "host"
    unrelated.mkdir()
    monkeypatch.chdir(unrelated)
    monkeypatch.setattr("integrations.github.repair_workspace.opensre_home", lambda: tmp_path)
    monkeypatch.setattr(
        "integrations.github.tools.ci_fix.storage.database.database_path",
        lambda: tmp_path / "repairs.db",
    )
    monkeypatch.setattr(
        "integrations.github.tools.ci_fix.runner.gather_ci_fix_context", lambda **_kw: ctx
    )
    monkeypatch.setattr(
        "integrations.github.tools.ci_fix.runner.verify_coding_agent", lambda: (True, "ready")
    )

    coding_calls: list[str] = []

    def code(_task: str, *, workspace: str, **_kwargs: object) -> CodingResult:
        coding_calls.append(workspace)
        (Path(workspace) / "calculator.py").write_text("def add(a, b): return a + b\n")
        return CodingResult(success=True, summary="Fix addition")

    checks_requested: list[str] = []

    def verify(_ctx: object, *, expected_head_sha: str, **_kwargs: object) -> CheckVerification:
        assert _git(remote, "rev-parse", "demo/failing-ci") == expected_head_sha
        assert "+ b" in _git(remote, "show", "demo/failing-ci:calculator.py")
        checks_requested.append(expected_head_sha)
        if len(checks_requested) == 1:
            raise RuntimeError("worker died after push")
        return CheckVerification(state=CheckState.PASSED, check_names=("unit",))

    monkeypatch.setattr("integrations.github.tools.ci_fix.runner.run_coding_task", code)
    monkeypatch.setattr("integrations.github.tools.ci_fix.runner.wait_for_pr_checks", verify)
    with pytest.raises(RuntimeError, match="worker died"):
        fix_github_pr_ci(owner="acme", repo="demo", pr_number=1, github_token="fixture")
    pushed = _git(remote, "rev-parse", "demo/failing-ci")
    monkeypatch.setattr(
        "integrations.github.tools.ci_fix.runner.gather_ci_fix_context",
        lambda **_kw: replace(ctx, head_sha=pushed),
    )
    output = fix_github_pr_ci(owner="acme", repo="demo", pr_number=1, github_token="fixture")
    assert output["success"], output
    assert output["fix_head_sha"] != ctx.head_sha
    assert output["work_outcome"]["status"] == "succeeded"
    assert len(coding_calls) == 1
    assert not list((tmp_path / "workspaces" / "repairs").glob("run-*"))
