"""Repository ownership and checkout lifetime for GitHub repairs."""

import hashlib
import re
import tempfile
from collections.abc import Iterator
from contextlib import ExitStack, contextmanager
from pathlib import Path

from filelock import FileLock, Timeout

from config.constants.paths import opensre_home
from integrations.git import (
    GitCommandError,
    clone_repository,
    ensure_git_repo,
    origin_push_urls,
    origin_url,
)
from integrations.github.identity import workspace_public_repository_source

_CHECKOUT_EXCLUDES = "\n__pycache__/\n*.py[cod]\n.pytest_cache/\n"


def ensure_repair_repository(workspace: str, owner: str, repo: str) -> None:
    """Require origin to identify the requested repository before any edits."""
    ensure_git_repo(workspace)
    for url in (origin_url(workspace), *origin_push_urls(workspace)):
        identity = workspace_public_repository_source({"workspace_repo": url})
        github = identity.get("github", {})
        actual = f"{github.get('owner', '')}/{github.get('repo', '')}"
        if actual.casefold() != f"{owner}/{repo}".casefold():
            raise GitCommandError(
                "repo_mismatch",
                f"Workspace origin is {actual}, but the repair targets {owner}/{repo}; no push was made.",
            )


@contextmanager
def repair_workspace(
    owner: str,
    repo: str,
    *,
    workspace: str | None = None,
    token: str | None = None,
    target: str = "",
    root: Path | None = None,
) -> Iterator[Path]:
    """Lease an explicit checkout or create an isolated, run-owned repository clone."""
    if any(not re.fullmatch(r"[A-Za-z0-9_-][A-Za-z0-9_.-]*", part) for part in (owner, repo)):
        raise GitCommandError("invalid_input", "Invalid GitHub repository identity.")
    base = root or opensre_home() / "workspaces" / "repairs"
    base.mkdir(parents=True, exist_ok=True)
    with ExitStack() as stack:
        identities = [f"{owner.casefold()}/{repo.casefold()}:{target}"] if target else []
        if workspace:
            path = Path(workspace).expanduser().resolve()
            ensure_repair_repository(str(path), owner, repo)
            identities.append(str(path))
        for identity in sorted(identities):
            key = hashlib.sha256(identity.encode()).hexdigest()
            try:
                stack.enter_context(FileLock(base / f"{key}.lock", timeout=0))
            except Timeout as exc:
                raise GitCommandError("workspace_busy", "Another repair owns this target.") from exc
        if not workspace:
            path = Path(stack.enter_context(tempfile.TemporaryDirectory(prefix="run-", dir=base)))
            clone_repository(f"https://github.com/{owner}/{repo}.git", str(path), token=token)
            ensure_repair_repository(str(path), owner, repo)
            # Local exclusions keep test-generated bytecode out of unattended commits;
            # tracked files and the repository's own ignore rules remain authoritative.
            with (path / ".git" / "info" / "exclude").open("a", encoding="utf-8") as stream:
                stream.write(_CHECKOUT_EXCLUDES)
        yield path
