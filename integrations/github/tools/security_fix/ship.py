"""Ship a GitHub security fix as branch, commit, push, and pull request."""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass

from integrations.coding_agent import CodingResult
from integrations.git import (
    GitCommandError,
    changed_paths,
    checkout_branch,
    commit_paths,
    create_branch,
    current_branch,
    default_branch,
    ensure_git_repo,
    file_fingerprints,
    push_branch,
    short_head,
)
from integrations.github.client import resolve_github_token
from integrations.github.pull_requests import (
    ERR_GITHUB_TOKEN as GH_PR_ERR_GITHUB_TOKEN,
)
from integrations.github.pull_requests import (
    GitHubPullRequestError,
    PullRequest,
    open_pull_request,
)
from integrations.github.tools.security_fix.context import SecurityAlertContext
from integrations.github.tools.security_fix.errors import (
    ERR_GITHUB_TOKEN,
    ERR_NO_CHANGES,
    ERR_PR_FAILED,
    GitHubSecurityFixError,
)

_BRANCH_PREFIX = "opensre/github-security-fix"
_FIX_BRANCH_RE = re.compile(
    rf"^{re.escape(_BRANCH_PREFIX)}-(?P<alert_type>[a-z_]+)-(?P<number>\d+)-[^/]+$"
)
_SUBJECT_MAX = 72
_MARKDOWN_HEADING_RE = re.compile(r"^#{1,6}\s*")
_SUBJECT_SKIP_LABELS = frozenset(
    {"summary", "root cause", "change", "changes", "verification", "test plan"}
)


@dataclass(frozen=True)
class ShipResult:
    """Outcome of shipping a GitHub security fix."""

    branch_name: str
    pr: PullRequest


def _slug(value: object) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_-]+", "-", str(value or "")).strip("-")
    return cleaned or "alert"


def build_branch_name(workspace: str, ctx: SecurityAlertContext) -> str:
    """Namespaced branch name for this fix."""
    suffix = short_head(workspace) or "wip"
    return f"{_BRANCH_PREFIX}-{_slug(ctx.alert_type)}-{_slug(ctx.number)}-{suffix}"


def parse_fix_branch_name(branch: str) -> tuple[str, int] | None:
    """Return ``(alert_type, number)`` from a :func:`build_branch_name` branch, else ``None``."""
    match = _FIX_BRANCH_RE.match(branch.strip())
    if match is None:
        return None
    return match.group("alert_type"), int(match.group("number"))


def _commit_message(ctx: SecurityAlertContext, summary: str) -> str:
    subject_tail = _subject_tail(summary, fallback=ctx.summary or "remediate finding")
    subject = (
        f"fix: remediate GitHub {ctx.alert_type.replace('_', ' ')} finding "
        f"#{ctx.number} - {subject_tail}"
    )[:_SUBJECT_MAX]
    lines = [subject, ""]
    if summary.strip():
        lines += [summary.strip(), ""]
    lines.append(f"Generated by OpenSRE from {ctx.url}.")
    return "\n".join(lines)


def _subject_tail(summary: str, *, fallback: str) -> str:
    """Pick a commit-subject fragment; skip markdown headings like ``## Summary``."""
    for raw in summary.strip().splitlines():
        line = _MARKDOWN_HEADING_RE.sub("", raw).strip().strip("*").strip()
        if not line or line.lower() in _SUBJECT_SKIP_LABELS:
            continue
        return line
    return fallback


def _pr_body(ctx: SecurityAlertContext, result: CodingResult, changed: Sequence[str]) -> str:
    lines = [
        (
            "Automated security or quality fix proposed by OpenSRE for "
            f"[{ctx.alert_type.replace('_', ' ')} finding #{ctx.number}]({ctx.url})."
        ),
        "",
        "**Alert summary**",
        ctx.summary.strip() or "_(no summary provided)_",
        "",
        "**Fix summary**",
        result.summary.strip() or "_(no summary provided)_",
    ]
    if changed:
        lines += ["", "**Files changed**"]
        lines += [f"- `{path}`" for path in changed]
    lines += [
        "",
        "> Generated by the OpenSRE `fix_github_security_alert` tool. Review before merging.",
    ]
    return "\n".join(lines)


def ship_security_fix(
    workspace: str,
    *,
    ctx: SecurityAlertContext,
    result: CodingResult,
    github_token: str | None = None,
    baseline: Mapping[str, str] | None = None,
) -> ShipResult:
    """Commit the security fix to a fresh branch, push it, and open a PR."""
    token = resolve_github_token(github_token)
    try:
        ensure_git_repo(workspace)
        pre_existing = dict(baseline or {})
        current = changed_paths(workspace)
        current_fingerprints = file_fingerprints(workspace, current)
        changed = [
            path
            for path in current
            if path not in pre_existing or current_fingerprints.get(path, "") != pre_existing[path]
        ]
        if not changed:
            reason = (
                "the fix run made no changes to the repository"
                if not current
                else "the fix run left no new changes"
            )
            raise GitHubSecurityFixError(
                ERR_NO_CHANGES,
                f"Nothing to commit - {reason}; nothing to open a PR for.",
            )

        base = default_branch(workspace, token=token or None)
        if not base:
            raise GitHubSecurityFixError(
                ERR_PR_FAILED,
                "Could not determine the base branch to open the PR against.",
            )
        branch = build_branch_name(workspace, ctx)
        if current_branch(workspace) != branch:
            checkout_branch(workspace, base)
            create_branch(workspace, branch, base_default=base)
    except GitCommandError as exc:
        raise GitHubSecurityFixError(exc.kind, exc.message) from exc

    try:
        commit_paths(workspace, changed, _commit_message(ctx, result.summary))
        push_branch(workspace, branch, base_default=base, token=token or None)
        pr = open_pull_request(
            workspace,
            head_branch=branch,
            base_branch=base,
            title=f"fix: remediate GitHub {ctx.alert_type.replace('_', ' ')} finding #{ctx.number}",
            body=_pr_body(ctx, result, changed),
            github_token=token or None,
        )
    except GitCommandError as exc:
        raise GitHubSecurityFixError(exc.kind, exc.message, branch_name=branch) from exc
    except GitHubPullRequestError as exc:
        kind = ERR_GITHUB_TOKEN if exc.kind == GH_PR_ERR_GITHUB_TOKEN else ERR_PR_FAILED
        raise GitHubSecurityFixError(kind, exc.message, branch_name=branch) from exc
    return ShipResult(branch_name=branch, pr=pr)


__all__ = ["ShipResult", "build_branch_name", "parse_fix_branch_name", "ship_security_fix"]
